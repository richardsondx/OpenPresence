import { expect, test } from "@playwright/test";

test("a Chat-style task without a calendar start survives projection, reload, and stays out of the calendar", async ({ page, request }) => {
  expect((await request.post("/api/state", { data: { type: "reset" } })).ok()).toBeTruthy();
  await page.goto("/");
  await page.getByLabel("Agent name").fill("Genny");
  await page.getByRole("button", { name: "Meet my Agent" }).click();
  const state = await (await request.get("/api/state")).json();
  const instruction = "Find a few posts worth quoting before 1 PM.";
  const created = await request.post("/api/state", { data: { type: "createAssignment", presenceId: state.presence.id, environment: "sandbox", instruction } });
  expect(created.ok()).toBeTruthy();
  const saved = await (await request.get("/api/state")).json();
  const task = saved.assignments.find((item: { instruction: string }) => item.instruction === instruction);
  expect(task.schedule).toBeUndefined();
  await page.goto(`/schedule?agentId=${state.agent.id}&presenceId=${state.presence.id}&assignmentId=${task.id}`);
  await expect(page.getByRole("heading", { name: "Task details", exact: true })).toBeVisible();
  await page.reload({ waitUntil: "domcontentloaded" });
  await expect(page.getByRole("heading", { name: "Task details", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.locator(".task-row").filter({ hasText: instruction })).toBeVisible();
  await page.getByRole("button", { name: "Calendar", exact: true }).click();
  await expect(page.getByRole("region", { name: "Weekly calendar" })).toBeVisible();
  await expect(page.getByRole("region", { name: "Tasks without a fixed start time" })).toHaveCount(0);
  await expect(page.getByRole("region", { name: "Weekly calendar" }).getByText(instruction, { exact: true })).toHaveCount(0);
});

test("a bounded task keeps its summary and window without a field editor", async ({ page, request }) => {
  expect((await request.post("/api/state", { data: { type: "reset" } })).ok()).toBeTruthy();
  await page.goto("/");
  await page.getByLabel("Agent name").fill("Genny");
  await page.getByRole("button", { name: "Meet my Agent" }).click();
  const state = await (await request.get("/api/state")).json();
  const startsAt = new Date(Date.now() + 3600000).toISOString();
  const deadline = new Date(Date.now() + 7200000).toISOString();
  const response = await request.post("/api/state", { data: { type: "createAssignment", presenceId: state.presence.id, environment: "sandbox", title: "Quote up to 3 useful posts", instruction: "Publish up to 3 quote posts about AI agents. Keep each quote useful.", timeframe: { startsAt, deadline } } });
  expect(response.ok()).toBeTruthy();
  const saved = await response.json();
  const task = saved.assignments.find((item: { title: string }) => item.title === "Quote up to 3 useful posts");
  await page.goto(`/schedule?agentId=${state.agent.id}&presenceId=${state.presence.id}&assignmentId=${task.id}`);
  await expect(page.getByRole("heading", { name: "Task details", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Edit Assignment", exact: true })).toHaveCount(0);
  await expect(page.getByLabel("Edit Assignment instruction")).toHaveCount(0);
  await expect(page.getByLabel("Tell Genny something about this", { exact: true })).toBeVisible();
  await page.reload({ waitUntil: "domcontentloaded" });
  await expect(page.getByRole("heading", { name: "Task details", exact: true })).toBeVisible();
  const updated = await (await request.get("/api/state")).json();
  const unchanged = updated.assignments.find((item: { id: string }) => item.id === task.id);
  expect(unchanged).toMatchObject({ title: "Quote up to 3 useful posts", instruction: "Publish up to 3 quote posts about AI agents. Keep each quote useful." });
  expect(Date.parse(unchanged.timeframe.deadline)).toBeGreaterThan(Date.parse(unchanged.timeframe.startsAt));
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Calendar", exact: true }).click();
  await expect(page.locator(".task-calendar-event").filter({ hasText: "Quote up to 3 useful posts" })).toBeVisible();
});

test("an expired task can be postponed conversationally and retains its identity after reload", async ({ page, request }) => {
  expect((await request.post("/api/state", { data: { type: "reset" } })).ok()).toBeTruthy();
  await page.goto("/");
  await page.getByLabel("Agent name").fill("Genny");
  await page.getByRole("button", { name: "Meet my Agent" }).click();
  const state = await request.get("/api/state").then(r => r.json());
  const created = await request.post("/api/state", { data: { type: "createAssignment", presenceId: state.presence.id, environment: "live", title: "Private retry test", instruction: "Prepare one private draft.", timeframe: { startsAt: new Date(Date.now() - 7200000).toISOString(), deadline: new Date(Date.now() - 3600000).toISOString() } } });
  expect(created.ok()).toBeTruthy();
  const task = (await created.json()).assignments.find((a: { title: string }) => a.title === "Private retry test");
  expect((await request.post("/api/state", { data: { type: "runLiveAssignment", presenceId: state.presence.id, assignmentId: task.id } })).ok()).toBeTruthy();
  await page.goto(`/schedule?agentId=${state.agent.id}&presenceId=${state.presence.id}&assignmentId=${task.id}`);
  await expect(page.getByRole("heading", { name: "Task details", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Cancel Assignment", exact: true })).toHaveCount(0);
  const newStart = new Date(Date.now() + 3600000);
  const local = (date: Date) => date.toISOString().slice(0, 10);
  const postponed = await request.post("/api/state", { data: { type: "planIntervention", assignmentId: task.id, action: "postpone", note: "Give this a new window tomorrow.", schedule: { date: local(newStart), day: newStart.toLocaleDateString("en-US", { weekday: "long" }), time: "08:00", executionWindow: "08:00–11:00" } } });
  expect(postponed.ok()).toBeTruthy();
  await page.reload();
  const after = await request.get("/api/state").then(r => r.json());
  const retry = after.assignments.find((a: { id: string }) => a.id === task.id);
  expect(retry.status).not.toBe("cancelled");
  expect(retry.schedule).toMatchObject({ date: local(newStart), time: "08:00" });
  expect(after.assignments.filter((a: { title: string }) => a.title === "Private retry test")).toHaveLength(1);
  expect(after.executions.filter((e: { assignmentId: string }) => e.assignmentId === task.id)).toHaveLength(0);
});
