import { expect, test } from "@playwright/test";

test("templates persist separately from analytics and can draft ideas without scheduling work", async ({ page, request }, testInfo) => {
  expect((await request.post("/api/state", { data: { type: "reset" } })).ok()).toBeTruthy();
  await page.goto("/");
  await page.getByLabel("Agent name").fill("Template Agent");
  await page.getByRole("button", { name: "Create Agent + Presence" }).click();
  const nav = page.getByRole("navigation", { name: /navigation$/ }).filter({ visible: true });
  await nav.getByRole("button", { name: "Artifacts", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Artifacts", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Create template", exact: true }).click();
  await page.getByLabel("Template name", { exact: true }).fill("Builder introduction");
  await page.getByLabel("Template", { exact: true }).fill("I’m [ROLE], building [PROJECT]. Looking to connect with [AUDIENCE].");
  await page.getByRole("button", { name: "Save template", exact: true }).click();
  await expect(page.getByText("Template saved.", { exact: false })).toBeVisible();
  await page.reload();
  const card = page.locator(".social-template-card").filter({ hasText: "Builder introduction" });
  await card.locator("summary").click();
  await expect(card).toContainText("Ready to test");
  await expect(card).toContainText("0 verified posts");
  await expect(card).toContainText("ROLE, PROJECT, AUDIENCE");
  const bounds = await page.locator(".artifacts-view").evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth }));
  expect(bounds.scroll).toBeLessThanOrEqual(bounds.width);
  await page.screenshot({ path: testInfo.outputPath("templates.png"), fullPage: true });
  await page.getByRole("tab", { name: "Media", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Media", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.reload();
  await expect(page.getByRole("tab", { name: "Media", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("tab", { name: "Templates", exact: true }).click();
  await card.locator("summary").click();
  await expect(card.getByRole("button", { name: "Schedule a task" })).toHaveCount(0);
  await expect(card.getByRole("button", { name: "Create scheduled task" })).toHaveCount(0);
  await nav.getByRole("button", { name: "Growth", exact: true }).click();
  await expect(page.locator('[aria-label="Growth profile"]')).toContainText("Audience model");
  await expect(page.getByRole("button", { name: "Create template", exact: true })).toHaveCount(0);
  await nav.getByRole("button", { name: "Artifacts", exact: true }).click();
  await card.locator("summary").click();
  await card.getByRole("button", { name: "Draft ideas", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Chat with Template Agent" })).toBeAttached();
  await expect(page.locator(".operator-chat-message.is-operator").last()).toContainText("Do not publish or schedule anything.");
});
